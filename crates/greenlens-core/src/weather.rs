//! Strict local EPW provider for the bounded v0.3 hourly daylight workflow.
//! The caller retains the original bytes; this module never reads a clock, path,
//! operating-system timezone, network service, or daylight-saving rule.
use crate::{canonical_hash, sha256, study::WeatherBinding, CoreError, Result};
use serde::{Deserialize, Serialize};
use std::collections::BTreeSet;

pub const WEATHER_SCHEMA: &str = "greenlens.weather.v0.3";
pub const WEATHER_HOURS: usize = 8760;
pub const MAX_EPW_BYTES: usize = 16 * 1024 * 1024;
const MONTH_DAYS: [u8; 12] = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];

/// Original, explicitly non-climatic full-year input for examples and service
/// tests. This arbitrary repeated day is not measured weather, a typical year,
/// or scientific evidence for the accuracy of annual daylight predictions.
/// It uses the explicit `EpwHourEnding` profile at a fictional equatorial site.
pub fn synthetic_epw() -> Vec<u8> {
    use std::fmt::Write;
    let mut text = String::from("LOCATION,Non-climatic synthetic example,Test,ZZZ,GreenLens original synthetic input,000000,0,0,0,0\nDESIGN CONDITIONS,0\nTYPICAL/EXTREME PERIODS,0\nGROUND TEMPERATURES,0\nHOLIDAYS/DAYLIGHT SAVING,No,0,0,0\nCOMMENTS 1,Arbitrary repeated day generated by GreenLens; not measurements or a climatic typical year\nCOMMENTS 2,Hourly interval-ending accumulations represented at midpoint; no source irradiation shift\nDATA PERIODS,1,1,Non-climatic example,Monday,1/1,12/31\n");
    for (month, days) in MONTH_DAYS.iter().enumerate() {
        for day in 1..=*days {
            for hour in 1..=24 {
                let (dni, dhi, ghi) = if (7..=18).contains(&hour) {
                    (400, 80, 280)
                } else {
                    (0, 0, 0)
                };
                writeln!(text, "2001,{},{day},{hour},60,?9?9?9,20,10,50,101325,9999,9999,300,{ghi},{dni},{dhi},999999,999999,999999,9999,180,2,5,5,9999,99999,9,999999999,999,0.999,999,99,999,999,99", month + 1).expect("Writing a String cannot fail");
            }
        }
    }
    text.into_bytes()
}

#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum WeatherSourceProfile {
    /// Explicit importer assertion: standard local-time hourly accumulations.
    EpwHourEnding,
    /// Reviewed PVGIS EPW convention, only the supported -0.5 h midpoint offset.
    PvgisTmy,
}
impl WeatherSourceProfile {
    pub fn interpretation(self) -> &'static str {
        match self {
            Self::EpwHourEnding => "greenlens.epw_hour_ending_midpoint.v1",
            Self::PvgisTmy => "greenlens.pvgis_tmy_epw_midpoint.v1",
        }
    }
    fn minute(self) -> u8 {
        match self {
            Self::EpwHourEnding => 60,
            Self::PvgisTmy => 0,
        }
    }
}

