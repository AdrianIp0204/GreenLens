#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
pub struct WeatherData {
    pub schema_version: String,
    pub original_sha256: String,
    pub normalized_sha256: String,
    pub time_axis_sha256: String,
    pub location: WeatherLocation,
    pub time_policy: WeatherTimePolicy,
    pub original_headers: Vec<String>,
    pub hours: Vec<WeatherHour>,
    pub summary: WeatherSummary,
    pub warnings: Vec<WeatherWarning>,
}
impl WeatherData {
    pub fn binding(&self) -> WeatherBinding {
        WeatherBinding {
            original_sha256: self.original_sha256.clone(),
            normalized_sha256: self.normalized_sha256.clone(),
            time_axis_sha256: self.time_axis_sha256.clone(),
            interpretation: self.time_policy.interpretation.clone(),
        }
    }
    pub fn interval(&self, index: usize) -> Result<WeatherInterval> {
        let h = self
            .hours
            .get(index)
            .ok_or_else(|| invalid(0, "interval_index", "Expected 0–8759"))?;
        if index >= WEATHER_HOURS || h.index != index {
            return Err(invalid(
                0,
                "interval_index",
                "Invalid normalized weather index",
            ));
        }
        let start = index as i32 * 60;
        let offset = i32::from(self.location.utc_offset_minutes);
        Ok(WeatherInterval {
            index,
            month: h.month,
            day: h.day,
            hour_ending: h.hour_ending,
            local_start_minute: start,
            local_end_minute: start + 60,
            local_representative_minute: start + 30,
            utc_start_minute: start - offset,
            utc_end_minute: start + 60 - offset,
            utc_representative_minute: start + 30 - offset,
        })
    }
}

/// Kept out of UI JSON: services persist the two EPW byte streams as files and
/// send only bounded metadata/slices to clients. Never deserialize WeatherData
/// as proof of validity: reparse original bytes and verify recorded identities.
#[derive(Debug, Clone)]
pub struct ParsedWeather {
    pub data: WeatherData,
    pub normalized_epw: Vec<u8>,
}

fn invalid(line: usize, field: &str, message: &str) -> CoreError {
    CoreError::Validation {
        field: if line == 0 {
            format!("weather.{field}")
        } else {
            format!("weather.line[{line}].{field}")
        },
        message: message.into(),
    }
}
fn finite(s: &str, line: usize, field: &str) -> Result<f64> {
    let value = s.parse::<f64>().map_err(|_| {
        invalid(
            line,
            field,
            "Expected a finite number; missing or malformed data is not zero",
        )
    })?;
    if !value.is_finite() {
        return Err(invalid(
            line,
            field,
            "NaN and infinite weather values are unsupported",
        ));
    }
    Ok(value)
}
fn integer(s: &str, line: usize, field: &str) -> Result<usize> {
    s.parse::<usize>()
        .map_err(|_| invalid(line, field, "Expected an unsigned whole number"))
}
fn range(value: f64, low: f64, high: f64, line: usize, field: &str) -> Result<f64> {
    if !(low..=high).contains(&value) {
        return Err(invalid(
            line,
            field,
            &format!("Expected {low} through {high}; got {value}"),
        ));
    }
    Ok(value)
}
fn fields(line: &str) -> Vec<&str> {
    line.split(',').map(str::trim).collect()
}
fn warn(warnings: &mut Vec<WeatherWarning>, code: &str, count: usize, message: &str) {
    if count > 0 {
        warnings.push(WeatherWarning {
            code: code.into(),
            count,
            message: message.into(),
        });
    }
}

fn irradiation_offset(headers: &[String]) -> Result<Option<f64>> {
    let marker = "irradiance time offset (h):";
    let mut found = None;
    for (i, text) in headers.iter().enumerate().skip(5).take(2) {
        let lower = text.to_ascii_lowercase();
        let declarations = lower.matches("irradiance time offset").count()
            + lower.matches("irradiation time offset").count();
        if declarations > 1 || (declarations > 0 && found.is_some()) {
            return Err(invalid(
                i + 1,
                "irradiance_offset",
                "Duplicate irradiation offset declarations",
            ));
        }
        if let Some(position) = lower.find(marker) {
            if found.is_some() {
                return Err(invalid(
                    i + 1,
                    "irradiance_offset",
                    "Duplicate irradiation offset declarations",
                ));
            }
            let rest = text[position + marker.len()..].trim();
            let token = rest
                .split(|c: char| c.is_whitespace() || c == ',')
                .next()
                .unwrap_or("");
            found = Some(finite(token, i + 1, "irradiance_offset")?);
        } else if lower.contains("irradiance time offset")
            || lower.contains("irradiation time offset")
        {
            return Err(invalid(i + 1, "irradiance_offset", "Unrecognized irradiation offset declaration; select a documented supported source format"));
        }
    }
    Ok(found)
}

/// Parse the declared source profile, retaining all original bytes by identity.
/// Normalization only removes UTF-8 BOM, trims CSV padding, uses LF, and changes
/// the reviewed PVGIS minute 0 marker to canonical hourly minute 60 and the
/// recognized singular HOLIDAYS header to Radiance's plural spelling. All 35
/// source values (including unused fields) and source-year labels are retained.
pub fn parse_epw(original: &[u8], profile: WeatherSourceProfile) -> Result<ParsedWeather> {
    if original.is_empty() || original.len() > MAX_EPW_BYTES {
        return Err(invalid(
            0,
            "bytes",
            "Expected a nonempty EPW no larger than 16 MiB",
        ));
    }
    let text = std::str::from_utf8(original)
        .map_err(|_| invalid(0, "encoding", "Expected UTF-8 or ASCII EPW text"))?;
    let text = text.strip_prefix('\u{feff}').unwrap_or(text);
    if text
        .chars()
        .any(|c| c.is_control() && !matches!(c, '\r' | '\n' | '\t'))
    {
        return Err(invalid(
            0,
            "encoding",
            "Unsupported control character in EPW",
        ));
    }
    let lines: Vec<&str> = text.lines().collect();
    if lines.len() != WEATHER_HOURS + 8 {
        return Err(invalid(0, "records", &format!("Expected exactly 8 headers and 8760 hourly records; got {} lines. Leap, incomplete, subhourly and multiyear files are unsupported", lines.len())));
    }
    if lines.iter().any(|l| l.len() > 16384 || l.trim().is_empty()) {
        return Err(invalid(
            0,
            "records",
            "Blank lines or lines over 16 KiB are unsupported",
        ));
    }
    let headers: Vec<String> = lines[..8].iter().map(|s| (*s).to_string()).collect();
    let keys = [
        "LOCATION",
        "DESIGN CONDITIONS",
        "TYPICAL/EXTREME PERIODS",
        "GROUND TEMPERATURES",
        "HOLIDAYS/DAYLIGHT SAVING",
        "COMMENTS 1",
        "COMMENTS 2",
        "DATA PERIODS",
    ];
    for (i, key) in keys.iter().enumerate() {
        let actual = fields(lines[i])[0];
        if actual != *key && !(i == 4 && actual == "HOLIDAYS/DAYLIGHT SAVINGS") {
            return Err(invalid(
                i + 1,
                "header",
                &format!("Expected {key} header in this position"),
            ));
        }
    }
    let loc = fields(lines[0]);
    if loc.len() != 10 || loc[1..6].iter().any(|v| v.is_empty()) {
        return Err(invalid(1, "location", "Expected 10 LOCATION fields with nonempty city, region, country, source and station (use an explicit unknown marker if unavailable)"));
    }
    if loc[1..5].iter().any(|v| v.len() > 63) || loc[5].len() > 15 {
        return Err(invalid(1, "location", "Pinned Radiance supports at most 63 UTF-8 bytes each for city/region/country/source and 15 for station; shorten a derived copy explicitly, never truncate silently"));
    }
    let tz = range(
        finite(loc[8], 1, "utc_offset_hours")?,
        -12.0,
        12.0,
        1,
        "utc_offset_hours",
    )? * 60.0;
    if (tz - tz.round()).abs() > 1e-7 {
        return Err(invalid(
            1,
            "utc_offset_hours",
            "Fixed UTC offset must resolve to whole minutes",
        ));
    }
    let elevation = finite(loc[9], 1, "elevation_m")?;
    if !(-1000.0..9999.9).contains(&elevation) {
        return Err(invalid(
            1,
            "elevation_m",
            "Expected elevation >= -1000 and < 9999.9 metres",
        ));
    }
    let location = WeatherLocation {
        city: loc[1].into(),
        region: loc[2].into(),
        country: loc[3].into(),
        source: loc[4].into(),
        station: loc[5].into(),
        latitude_deg_north: range(finite(loc[6], 1, "latitude")?, -90.0, 90.0, 1, "latitude")?,
        longitude_deg_east: range(
            finite(loc[7], 1, "longitude")?,
            -180.0,
            180.0,
            1,
            "longitude",
        )?,
        utc_offset_minutes: tz.round() as i16,
        elevation_m: elevation,
    };
    for (i, line) in lines.iter().enumerate().take(4).skip(1) {
        let f = fields(line);
        if f.len() < 2 {
            return Err(invalid(
                i + 1,
                "header_count",
                "Missing ancillary header count",
            ));
        }
        integer(f[1], i + 1, "header_count")?;
    }
    let holidays = fields(lines[4]);
    if holidays.len() < 5 || !holidays[1].eq_ignore_ascii_case("no") {
        return Err(invalid(
            5,
            "leap_year",
            "Only a non-leap EPW with LeapYear Observed=No is supported",
        ));
    }
    let holiday_count = integer(holidays[4], 5, "holiday_count")?;
    if holiday_count > 366 || holidays.len() != 5 + holiday_count * 2 {
        return Err(invalid(
            5,
            "holiday_count",
            "Holiday count does not match header fields",
        ));
    }
    let periods = fields(lines[7]);
    if periods.len() != 7 || periods[1] != "1" || periods[2] != "1" {
        return Err(invalid(
            8,
            "data_periods",
            "Exactly one data period and one record per hour are required",
        ));
    }
    let date = |s: &str| -> Option<(usize, usize)> {
        let v: Vec<_> = s.split('/').map(str::trim).collect();
        if v.len() != 2 {
            return None;
        }
        Some((v[0].parse().ok()?, v[1].parse().ok()?))
    };
    if date(periods[5]) != Some((1, 1)) || date(periods[6]) != Some((12, 31)) {
        return Err(invalid(8, "data_period_dates", "Expected 1/1 through 12/31 without calendar years; partial and multiyear axes are unsupported"));
    }
    if periods[3].is_empty()
        || periods[3].len() > 63
        || ![
            "Sunday",
            "Monday",
            "Tuesday",
            "Wednesday",
            "Thursday",
            "Friday",
            "Saturday",
        ]
        .iter()
        .any(|d| periods[4].eq_ignore_ascii_case(d))
    {
        return Err(invalid(8, "data_period", "Expected period name and weekday label; the weekday is retained but never used for occupancy"));
    }
    let declared_offset = irradiation_offset(&headers)?;
    if declared_offset.is_some_and(|x| (x + 0.5).abs() > 1e-9) {
        return Err(invalid(7, "irradiance_offset", "Only an interval-end-relative -0.5 hour midpoint offset is supported; do not reinterpret or shift this source silently"));
    }
    if profile == WeatherSourceProfile::PvgisTmy && declared_offset.is_none() {
        return Err(invalid(
            7,
            "irradiance_offset",
            "PVGIS profile requires COMMENTS 2 Irradiance Time Offset (h):-0.5",
        ));
    }
    let time_policy = WeatherTimePolicy {
        profile,
        interpretation: profile.interpretation().into(),
        source_minute: profile.minute(),
        canonical_minute: 60,
        interval_duration_minutes: 60,
        representative_offset_from_interval_end_minutes: -30,
        declared_irradiance_offset_hours: declared_offset,
        fixed_local_standard_time: true,
        source_year_is_calendar: false,
        applies_daylight_saving: false,
    };
    let mut canonical_headers = lines[..8]
        .iter()
        .map(|l| fields(l).join(","))
        .collect::<Vec<_>>();
    if canonical_headers[4].starts_with("HOLIDAYS/DAYLIGHT SAVING,") {
        canonical_headers[4] = canonical_headers[4].replacen(
            "HOLIDAYS/DAYLIGHT SAVING,",
            "HOLIDAYS/DAYLIGHT SAVINGS,",
            1,
        );
    }
    if canonical_headers.iter().any(|line| line.len() > 1022) {
        return Err(invalid(0, "header_bytes", "A normalized header exceeds the pinned Radiance 1022-byte line limit; no truncation is performed"));
    }
    let mut normalized = canonical_headers.join("\n");
    normalized.push('\n');
    let mut hours = Vec::with_capacity(WEATHER_HOURS);
    let mut years: Vec<BTreeSet<u16>> = (0..12).map(|_| BTreeSet::new()).collect();
    let mut zero_solar = 0;
    let mut totals = [0.0; 3];
    let mut dew_min = f64::INFINITY;
    let mut dew_max = f64::NEG_INFINITY;
    let mut negative_unused_ir = 0;
    let mut invalid_unused_wind = 0;
    let mut ghi_inconsistent = 0;
    let mut expected_month = 1u8;
    let mut expected_day = 1u8;
    for (index, line) in lines[8..].iter().enumerate() {
        let line_number = index + 9;
        let mut f = fields(line);
        if f.len() != 35 {
            return Err(invalid(
                line_number,
                "fields",
                "Expected exactly 35 comma-separated EPW fields",
            ));
        }
        let year = integer(f[0], line_number, "source_year")?;
        if !(1..=9999).contains(&year) {
            return Err(invalid(
                line_number,
                "source_year",
                "Expected a source year 1–9999; it is provenance, not the simulation calendar",
            ));
        }
        let expected_hour = (index % 24 + 1) as u8;
        let (month, day, hour, minute) = (
            integer(f[1], line_number, "month")?,
            integer(f[2], line_number, "day")?,
            integer(f[3], line_number, "hour")?,
            integer(f[4], line_number, "minute")?,
        );
        if (month, day, hour)
            != (
                usize::from(expected_month),
                usize::from(expected_day),
                usize::from(expected_hour),
            )
        {
            return Err(invalid(line_number, "timestamp", &format!("Expected {expected_month:02}/{expected_day:02} hour {expected_hour}; duplicate, missing, reordered or leap intervals are unsupported")));
        }
        if minute != usize::from(profile.minute()) {
            return Err(invalid(line_number, "minute", &format!("Profile {:?} requires minute {}; source conventions cannot be guessed or mixed", profile, profile.minute())));
        }
        if f[5].is_empty() || f[5].len() > 63 {
            return Err(invalid(
                line_number,
                "source_flags",
                "Source/uncertainty flags must contain 1–63 bytes for the pinned Radiance reader",
            ));
        }
        // Even unused fields must be lexical finite numbers so Radiance's EPW
        // reader cannot terminate early. Their sentinels remain intact.
        let mut numbers = [0.0; 29];
        for (i, token) in f.iter().enumerate().skip(6) {
            numbers[i - 6] = finite(token, line_number, &format!("field_{}", i + 1))?;
            if !(numbers[i - 6] as f32).is_finite() {
                return Err(invalid(
                    line_number,
                    &format!("field_{}", i + 1),
                    "Value exceeds the pinned engine's finite single-precision range",
                ));
            }
        }
        let dew = numbers[1];
        if dew >= 99.9 || !(-70.0..70.0).contains(&dew) || dew == -70.0 {
            return Err(invalid(line_number, "dew_point_c", "Required sky-model dew point must be > -70 and < 70 C; missing sentinel 99.9 is rejected"));
        }
        let mut solar = [0.0; 3];
        for (j, (i, name)) in [
            (14, "direct_normal"),
            (15, "diffuse_horizontal"),
            (13, "global_horizontal"),
        ]
        .iter()
        .enumerate()
        {
            let value = numbers[i - 6];
            if !(0.0..9999.0).contains(&value) || (value != 0.0 && value as f32 == 0.0) {
                return Err(invalid(line_number, name, "Required radiation must be >=0 and <9999 Wh/m2; missing sentinels are rejected, never treated as night"));
            }
            solar[j] = value;
            totals[j] += value;
        }
        if solar[0] == 0.0 && solar[1] == 0.0 {
            zero_solar += 1;
        }
        if solar[1] > solar[2] + 0.1 || (solar[0] == 0.0 && solar[1] == 0.0 && solar[2] > 0.1) {
            ghi_inconsistent += 1;
        }
        if numbers[6] < 0.0 {
            negative_unused_ir += 1;
        }
        if !(0.0..=40.0).contains(&numbers[15]) && numbers[15] < 999.0 {
            invalid_unused_wind += 1;
        }
        dew_min = dew_min.min(dew);
        dew_max = dew_max.max(dew);
        years[month - 1].insert(year as u16);
        hours.push(WeatherHour {
            index,
            source_year: year as u16,
            month: month as u8,
            day: day as u8,
            hour_ending: hour as u8,
            source_minute: minute as u8,
            direct_normal_wh_m2: solar[0],
            diffuse_horizontal_wh_m2: solar[1],
            global_horizontal_wh_m2: solar[2],
            dew_point_c: dew,
        });
        f[4] = "60";
        let canonical_row = f.join(",");
        if canonical_row.len() > 1022 {
            return Err(invalid(
                line_number,
                "record_bytes",
                "Normalized record exceeds the pinned Radiance 1022-byte line limit",
            ));
        }
        normalized.push_str(&canonical_row);
        normalized.push('\n');
        if expected_hour == 24 {
            expected_day += 1;
            if expected_day > MONTH_DAYS[usize::from(expected_month - 1)] {
                expected_day = 1;
                expected_month += 1;
            }
        }
    }
    let normalized_epw = normalized.into_bytes();
    let mut warnings = Vec::new();
    warn(&mut warnings, "unused_negative_infrared", negative_unused_ir, "Negative infrared values are retained. They are not consumed by the daylight sky route; this import is not validation for energy or thermal analysis.");
    warn(&mut warnings, "unused_invalid_wind", invalid_unused_wind, "Out-of-range wind values are retained and unused by daylight. No wind/thermal suitability is claimed.");
    warn(&mut warnings, "ghi_consistency", ghi_inconsistent, "GHI/DHI consistency differs by more than 0.1 Wh/m2. Original values are retained; the canonical sky consumes DNI/DHI, not GHI. Review the source before interpreting results.");
    warn(&mut warnings, "daylight_saving_metadata_ignored", usize::from(holidays[2] != "0" || holidays[3] != "0"), "EPW daylight-saving metadata is retained but ignored; calculations and occupancy use fixed local standard time.");
    warn(&mut warnings, "holidays_metadata_ignored", holiday_count, "EPW holiday metadata is retained but not used for occupancy; typical-year source years do not define a weekday schedule.");
    let axis: Vec<_> = hours
        .iter()
        .map(|h| (h.index, h.month, h.day, h.hour_ending, h.index * 60 + 30))
        .collect();
    let data = WeatherData {
        schema_version: WEATHER_SCHEMA.into(),
        original_sha256: sha256(original),
        normalized_sha256: sha256(&normalized_epw),
        time_axis_sha256: canonical_hash(&(
            "greenlens.fixed_local_nonleap_hourly_axis.v1",
            location.utc_offset_minutes,
            &axis,
        ))?,
        location,
        time_policy,
        original_headers: headers,
        hours,
        summary: WeatherSummary {
            intervals: WEATHER_HOURS,
            source_years_by_month: years.into_iter().map(|s| s.into_iter().collect()).collect(),
            zero_solar_intervals: zero_solar,
            direct_normal_total_wh_m2: totals[0],
            diffuse_horizontal_total_wh_m2: totals[1],
            global_horizontal_total_wh_m2: totals[2],
            minimum_dew_point_c: dew_min,
            maximum_dew_point_c: dew_max,
        },
        warnings,
    };
    Ok(ParsedWeather {
        data,
        normalized_epw,
    })
}
